rt.def("/obj/item/device/forcefield/proc/process", function* process(f: Frame) {
	let F: Value = null;
	if (!rt.length(this.current_fields)) {
		this.shield_integrity = min(this.shield_integrity + 4, this.max_shield_integrity);
	} else {
		this.shield_integrity = max(this.shield_integrity - rt.length(this.current_fields), 0);
	}
	for (F of each(this.current_fields, T("/obj/structure/projected_forcefield"))) {
		if (this.shield_integrity <= 0 || get_dist(F, this) > this.field_distance_limit) {
			yield* qdel(F);
		}
	}
	return f.dot;
}, true, { waitfor: false });

