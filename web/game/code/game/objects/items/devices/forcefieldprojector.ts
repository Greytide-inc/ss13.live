rt.def("/obj/item/device/forcefield/proc/afterattack", function* afterattack(f: Frame, target: Value, user: Value, proximity_flag: Value) {
	let F: Value = null, _T: Value = null, F_1: Value = null;
	if (!this.check_allowed_items(target, 1)) {
		return f.dot;
	}
	if (rt.istype(target, T("/obj/structure/projected_forcefield"))) {
		if ((F = target).generator == this) {
			to_chat(user, `<span class='notice'>You deactivate ${F}.</span>`);
			yield* qdel(F);
			return f.dot;
		}
	}
	if ((_T = rt.getStep(f, target, 0)).density) {
		return f.dot;
	}
	if (get_dist(_T, this) > this.field_distance_limit) {
		return f.dot;
	}
	if (rt.length(this.current_fields) >= this.max_fields) {
		to_chat(user, `<span class='notice'>${this} cannot sustain any more forcefields!</span>`);
		return f.dot;
	}
	playsound(this, rt.rsc("sound/weapons/resonator_fire.ogg"), 50, 1);
	user.visible_message(`<span class='warning'>${user} projects a forcefield!</span>`, "<span class='notice'>You project a forcefield.</span>");
	this.current_fields += (F_1 = (yield* new_(T("/obj/structure/projected_forcefield"), _T, this)));
	user.changeNext_move(8);
	return f.dot;
}, true);

