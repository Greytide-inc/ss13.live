/** Names bound by a declaration or assignment target (`x`, `[a, b]`, `{ a, b: c }`). */
const boundNames = (n, out = []) => {
	if (ts.isIdentifier(n)) out.push(n.text);
	else if (ts.isObjectBindingPattern(n) || ts.isArrayBindingPattern(n)) for (const e of n.elements) { if (!ts.isOmittedExpression(e)) boundNames(e.name, out); }
	else if (ts.isArrayLiteralExpression(n)) for (const e of n.elements) boundNames(ts.isSpreadElement(e) ? e.expression : e, out);
	else if (ts.isObjectLiteralExpression(n)) for (const p of n.properties) boundNames(ts.isShorthandPropertyAssignment(p) ? p.name : ts.isPropertyAssignment(p) ? p.initializer : ts.isSpreadAssignment(p) ? p.expression : p, out);
	return out;
};
/**
 * dt-tidy f-vars (detranslate 7b): a proc's (or tail's) `f.vars = () => [...]`, the locals the collector marks (VM gcSafePoint,
 * snapshots), is written here, not in game/: its arguments that the body assigns (the others are f.args) and every name its
 * body declares at the top level. It goes right after the last top-level declaration (all of them are set by then, so the
 * list never reads one before its `let`), else at the end of the function's first line; nothing is listed, nothing goes in.
 * A later run of declarations (pb-tidy2 moved lets) gets its own f.vars with all the names so far. Returns the insertion cuts, or null. Declarations inside blocks can't be listed: declare a local that may hold an object
 * across a sleep or a del at the top (`let x: Value = null;`).
 */
function varsCut(fn, sf, text, stop, addE) {
	const written = new Set();
	const visit = (n) => {
		if (ts.isBinaryExpression(n) && n.operatorToken.kind >= ts.SyntaxKind.FirstAssignment && n.operatorToken.kind <= ts.SyntaxKind.LastAssignment) for (const x of boundNames(n.left)) written.add(x);
		else if ((ts.isPrefixUnaryExpression(n) || ts.isPostfixUnaryExpression(n)) && (n.operator === ts.SyntaxKind.PlusPlusToken || n.operator === ts.SyntaxKind.MinusMinusToken) && ts.isIdentifier(n.operand)) written.add(n.operand.text);
		else if ((ts.isForOfStatement(n) || ts.isForInStatement(n)) && !ts.isVariableDeclarationList(n.initializer)) for (const x of boundNames(n.initializer)) written.add(x);
		if (ts.isBinaryExpression(n) && ts.isPropertyAccessExpression(n.left) && n.left.getText(sf) === "f.vars") stop(n, "f.vars is written by translate-tg (detranslate 7b): delete this line");
		ts.forEachChild(n, visit);
	};
	visit(fn.body);
	const names = [];
	for (const p of fn.parameters.slice(1)) for (const x of boundNames(p.name)) if (written.has(x)) names.push(x);
	// pb-temps: a `const` that only the conditions of the if-chain right after it read (a switch subject) never holds anything across a
	// call or a sleep, so it is no root and does not move the anchor
	const sts = fn.body.statements;
	const isSubject = (st, i) => {
		const dl = st.declarationList, d = dl.declarations[0], nx = sts[i + 1];
		if (!(dl.flags & ts.NodeFlags.Const) || dl.declarations.length !== 1 || !ts.isIdentifier(d.name) || !nx || !ts.isIfStatement(nx)) return false;
		const conds = [];
		for (let c = nx; c && ts.isIfStatement(c); c = c.elseStatement) conds.push(c.expression);
		let ok = true;
		const v = (n) => { if (ts.isIdentifier(n) && n.text === d.name.text && n !== d.name && !conds.some((c) => n.pos >= c.pos && n.end <= c.end)) ok = false; ts.forEachChild(n, v); };
		v(fn.body);
		return ok;
	};
	// pb-tidy2: a `let` moved down to its first write is a top-level declaration far from the head. f.vars goes after every run of top-level
	// declarations and lists the names declared so far (a later one can't be listed earlier: its `let` hasn't run, and before its first
	// write it held null, no root either); a proc with all its lets at the head still gets one, as before.
	const runs = []; // [{ end: last statement of a run, names so far }]
	let cur = null;
	sts.forEach((st, i) => {
		if (ts.isVariableStatement(st) && !isSubject(st, i)) {
			for (const d of st.declarationList.declarations) boundNames(d.name, names);
			cur = { end: st, names: [...names] };
			if (runs.length && runs[runs.length - 1].end === sts[i - 1]) runs[runs.length - 1] = cur; else runs.push(cur);
		}
	});
	if (addE) { names.push("$e"); for (const r of runs) r.names.push("$e"); } // dt-loops: the proc's plain list loops need the translator's `let $e;`, the last declaration
	if (!names.length) return null;
	if (!runs.length) runs.push({ end: null, names: [...names] });
	return runs.map((r, k) => {
		const at = r.end ? r.end.end : fn.body.getStart(sf) + 1, eol = text.indexOf("\n", at);
		if (/\S/.test(text.slice(at, eol < 0 ? text.length : eol).replace(/\/\/.*$/, ""))) stop(r.end ?? fn.body, "f.vars goes at the end of this line, so nothing else may follow on it (its columns would move)");
		return [at, at, `${addE && k === 0 ? " let $e;" : ""} f.vars = () => [${r.names.join(", ")}];`];
	});
}
function blankTypes(f, text) {
	const sf = ts.createSourceFile(f, text, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);
	const cuts = [], defs = [], procPaths = [], procIndex = new Map(), gSites = [], rtSites = [], svNames = [];
	let hasGl = false;
	const rewrote = tally;
	const aliases = rtAliases(sf);
	const names = { ...callNames, scope: scopeNames(sf) };
	const stop = (n, why) => { throw new Error(`${relative(web, f)}:${sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1}: ${why}: ${n.getText(sf).slice(0, 60)}`); };
	const unsupported = (n) => { throw new Error(`${relative(web, f)}:${sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1}: TypeScript syntax the bundle can't blank out: ${n.getText(sf).slice(0, 60)}`); };
	/**
	 * dt-named (detranslate step 10a): the last argument `{ key: value, ... }` of a proc call is its named arguments: the old call's
	 * `"key", value` pairs after the positional `null, value` ones, and the call ends `], rt.Args.Named)`. Anything but plain
	 * `key: value` properties (a spread, a computed key, a method, a shorthand `{ target }`) or a line break in the braces stops the build.
	 */
	const lowerNamed = (o) => {
		const ps = o.properties;
		tally("named arguments");
		if (!ps.length || ps.some((p) => !ts.isPropertyAssignment(p) || !(ts.isIdentifier(p.name) || ts.isStringLiteral(p.name))))
			stop(o, "named arguments `{ key: value }` take plain `key: value` properties (no ...spread, [computed] key, method or shorthand)");
		const first = ps[0].getStart(sf), last = ps[ps.length - 1];
		if (/\n/.test(text.slice(o.getStart(sf), first)) || ps.some((p) => /\n/.test(text.slice(p.name.getStart(sf), p.initializer.getStart(sf)))))
			stop(o, "named arguments: the `{` and each `key:` must be on the line of their value");
		cuts.push([o.getStart(sf), first, ""]);
		for (const p of ps) { cuts.push([p.name.getStart(sf), p.initializer.getStart(sf), `${JSON.stringify(p.name.text)}, `]); visit(p.initializer); }
		cuts.push([last.end, o.end, ""]);
	};
	/**
	 * dt-calls (detranslate step 8): a proc call as written by hand (proc-calls.mjs readableCall) -> the engine call it stands for,
	 * spelled as the translator wrote it: `A.x(a)` -> `$M.sK(f, A, "x", [a])` (rt.callName's cached site; `$.sK`, g.callName, under
	 * yield*), `this.x(a)` -> rt.callSrc / g.srcCall, `x(a)` -> rt.call / g.call(f, $P[k], null, [a]), `parent_proc()` -> callSuper(f,
	 * [], rt.Args.Same) (`[]` in an <init>). Longer than the source, but on the same line.
	 */
	const lowerCall = (n, rc) => {
		const fn = procFunction(n), near = nearestFunction(n);
		if (!fn) stop(n, "a proc call outside rt.def/rt.tail (no frame f to make it with)");
		const gen = !!near.asteriskToken, yielded = ts.isYieldExpression(n.parent) && !!n.parent.asteriskToken;
		// dt-yields (detranslate step 9f): in a function* a call that can't pause is written without yield*; the bundle adds it
		if (gen && !yielded && callCanWait(rc, names)) stop(n, `${rc.name}() can pause (a sleep in it or in an override): a call to it in a function* needs yield*`);
		const added = gen && !yielded, own = added && ts.isExpressionStatement(n.parent);
		if (added) cuts.push([n.getStart(sf), n.getStart(sf), own ? "yield* " : "(yield* "]);
		if (rc.kind === "src" && thisFunction(n) !== fn) stop(n, "this.x() inside a nested function, where this isn't src");
		if (n.arguments.some(ts.isSpreadElement)) stop(n, "a proc call with ...spread arguments");
		const nobj = namedObj(n), pos = nobj ? n.arguments.slice(0, -1) : n.arguments, tail = nobj ? "], rt.Args.Named)" : "])";
		for (const x of pos) if (ts.isObjectLiteralExpression(x)) stop(x, "named arguments `{ key: value }` must be the last argument of a proc call");
		const close = n.end - 1, open = n.arguments.pos, e = n.expression, a = e.getStart(sf);
		if (text[close] !== ")" || text[open - 1] !== "(") stop(n, "a proc call the bundler can't take apart");
		if (/\n/.test(text.slice(rc.kind === "name" ? rc.recv.end : a, open))) stop(n, "a proc call's name and ( must be on its receiver's line");
		const pre = gen ? "g" : "rt", none = n.arguments.length === 0;
		rewrote(`call: ${rc.kind}`);
		if (added) tally("call: yield* added");
		if (rc.kind === "name" || rc.kind === "src") {
			const sites = gen ? gSites : rtSites, obj = gen ? "$" : "$M", k = sites.length;
			sites.push(rc.kind === "name" ? (gen ? "n" : "N") : gen ? (nobj ? "s" : "t") : "S");
			const head = `${obj}.s${k}(f, `;
			if (rc.kind === "name") {
				const r = rc.recv.getStart(sf);
				cuts.push([r, r, head]);
				cuts.push([rc.recv.end, open, `, ${JSON.stringify(rc.name)}, [`]);
				cuts.push([close, n.end, tail]);
				visit(rc.recv);
			} else if (gen && !nobj) cuts.push([a, open, `${head}${JSON.stringify(rc.name)}${none ? "" : ", "}`]);
			else {
				cuts.push([a, open, `${head}${JSON.stringify(rc.name)}, [`]);
				cuts.push([close, n.end, tail]);
			}
		} else if (rc.kind === "global") {
			const path = `/proc/${rc.name}`;
			let k = procIndex.get(path);
			if (k === undefined) { k = procPaths.length; procIndex.set(path, k); procPaths.push(path); }
			cuts.push([a, open, `${pre}.call(f, $P[${k}], null, [`]);
			cuts.push([close, n.end, tail]);
		} else if (none) {
			const init = fn.parent.arguments[0].text.endsWith("/<init>");
			cuts.push([a, n.end, `${pre}.callSuper(f, []${init ? "" : ", rt.Args.Same"})`]);
		} else {
			cuts.push([a, open, `${pre}.callSuper(f, [`]);
			cuts.push([close, n.end, tail]);
		}
		for (const x of pos) { if (nobj) cuts.push([x.getStart(sf), x.getStart(sf), "null, "]); visit(x); }
		if (nobj) lowerNamed(nobj);
		if (added && !own) cuts.push([n.end, n.end, ")"]);
	};
	/**
	 * dt-vars (detranslate step 9a): a DM var read or `=` written by hand (proc-calls.mjs readableVar) -> the call the translator
	 * wrote, as the rt.fv / rt.setFv / rt.sv / rt.setSv lowerings below make it: `X.name` -> `$g(f,$q[K],X)`, `X.name = v` ->
	 * `$F(f,$q[K],X, v)`, `this.loc` -> `$v(f,$q[K])`, `this.loc = v` -> `$s(f,$q[K],v)`. Longer than the source, like a call.
	 * `+=` and `++` are lowerOp's; any other write (delete, a loop variable,
	 * `&&=`) stops the build.
	 */
	const lowerVar = (n, rv, assign) => {
		const p = n.parent;
		if (!assign && ((ts.isBinaryExpression(p) && p.left === n && p.operatorToken.kind >= ts.SyntaxKind.FirstAssignment && p.operatorToken.kind <= ts.SyntaxKind.LastAssignment)
			|| ((ts.isPrefixUnaryExpression(p) || ts.isPostfixUnaryExpression(p)) && (p.operator === ts.SyntaxKind.PlusPlusToken || p.operator === ts.SyntaxKind.MinusMinusToken))
			|| ts.isDeleteExpression(p) || ((ts.isForInStatement(p) || ts.isForOfStatement(p)) && p.initializer === n)))
			stop(n, `a DM var written other than by \`=\` or DM's operators (delete, a loop variable, &&=): write it with rt.setFv / rt.modField`);
		const k = svNames.length, s0 = n.getStart(sf);
		svNames.push(rv.name);
		rewrote(`var ${assign ? "write" : "read"}: ${rv.kind}`);
		if (rv.kind === "src") {
			if (thisFunction(n) !== procFunction(n)) stop(n, "this.x inside a nested function, where this isn't src");
			if (procMovesSrc(n)) stop(n, `this.${rv.name} in a proc that assigns f.src: write rt.sv / rt.setSv`);
			if (assign) { cuts.push([s0, assign.right.getStart(sf), `$s(f,$q[${k}],`]); cuts.push([assign.end, assign.end, ")"]); visit(assign.right); }
			else { cuts.push([s0, n.end, `$v(f,$q[${k}])`]); }
			return;
		}
		const r = rv.recv, a = r.getStart(sf);
		if (assign) {
			cuts.push([a, a, `$F(f,$q[${k}],`]); cuts.push([r.end, assign.right.getStart(sf), ", "]); cuts.push([assign.end, assign.end, ")"]);
			visit(r); visit(assign.right);
		} else {
			cuts.push([a, a, `$g(f,$q[${k}],`]); cuts.push([r.end, n.end, ")"]);
			visit(r);
		}
	};
	/**
	 * dt-globals (detranslate step 9g): `GLOB.name` in a proc is the DM global `name` (proc-calls.mjs readableGlobal) -> `$gl(K)`,
	 * `GLOB.name = v` -> `$sl(K, v)`, as the rt.gl / rt.setGl lowerings below make them (K = its index in game/_globals.ts); `+=` and
	 * `++` are lowerOp's ($ml, $il). Any other write (delete, a loop variable, &&=) stops the build. Lines change length, like a call's.
	 */
	const globIndex = (n, name) => {
		const k = glKeys.get(name);
		if (k === undefined) stop(n, `GLOB.${name}: no such global in game/_globals.ts`);
		hasGl = true;
		rewrote("GLOB.x");
		return k;
	};
	const lowerGlobal = (n, name, assign) => {
		const p = n.parent;
		if (!assign && ((ts.isBinaryExpression(p) && p.left === n && p.operatorToken.kind >= ts.SyntaxKind.FirstAssignment && p.operatorToken.kind <= ts.SyntaxKind.LastAssignment)
			|| ((ts.isPrefixUnaryExpression(p) || ts.isPostfixUnaryExpression(p)) && (p.operator === ts.SyntaxKind.PlusPlusToken || p.operator === ts.SyntaxKind.MinusMinusToken))
			|| ts.isDeleteExpression(p) || ((ts.isForInStatement(p) || ts.isForOfStatement(p)) && p.initializer === n)))
			stop(n, "a DM global written other than by `=` or DM's operators (delete, a loop variable, &&=): write it with rt.setGl / rt.modGl");
		const k = globIndex(n, name), s0 = n.getStart(sf);
		if (assign) {
			if (/\n/.test(text.slice(s0, assign.right.getStart(sf)))) stop(n, "GLOB.x = split over lines before its value");
			cuts.push([s0, assign.right.getStart(sf), `$sl(${k}, `]);
			visit(assign.right);
			cuts.push([assign.end, assign.end, ")"]);
		} else { cuts.push([s0, n.end, `$gl(${k})`]); }
	};
	/**
	 * dt-ops (detranslate step 9b): an operator in a proc is DM's (proc-calls.mjs DM_BINARY) -> its runtime call, as the
	 * translator wrote it: `a + b` -> `add(a , b)` (the operator becomes the comma, so lines keep their breaks), `-a` -> `rt.neg(a)`,
	 * `x op= v` -> `x = rt.modify(x, v, add)` / `rt.modSrcVar(f, "x", v, add)` / `rt.modField(f, o, "x", v, add)`, `x++` ->
	 * `x = rt.inc(x, 1)` / `rt.incSrcVar(f, "x", 1, true)` / `rt.incField(f, o, "x", 1, true)`. Longer than the source, like a call.
	 */
	const opFn = (fn, n) => opFunction(fn, n, aliases, names.scope);
	const opTok = (n) => [n.operatorToken.getStart(sf), n.operatorToken.end];
	const target = (x, n) => {
		if (x.kind === ts.SyntaxKind.ThisKeyword) return null;
		if (ts.isPropertyAccessExpression(x) && x.expression.kind === ts.SyntaxKind.ThisKeyword && ts.isIdentifier(x.name)) {
			if (thisFunction(n) !== procFunction(n)) stop(n, "this.x inside a nested function, where this isn't src");
			if (procMovesSrc(n)) stop(n, `this.${x.name.text} in a proc that assigns f.src: write rt.modSrcVar / rt.incSrcVar`);
			return { kind: "src", name: x.name.text };
		}
		const gn = readableGlobal(x, names.scope);
		if (gn) return { kind: "glob", k: globIndex(x, gn) };
		const rv = readableVar(x, names);
		if (rv && rv.kind === "field") return { kind: "field", name: rv.name, recv: rv.recv };
		if (plainTarget(x)) return { kind: "plain", text: x.getText(sf) };
		stop(n, "DM's x op= v / x++ on something other than a local, f.dot, this.x or a DM var (lists: rt.modAt / rt.incAt)");
	};
	const lowerOp = (n) => {
		rewrote(ts.isBinaryExpression(n) ? ((DM_BINARY[n.operatorToken.kind] || DM_NEGATED[n.operatorToken.kind]) ? "operator: a + b" : "operator: x += v") : n.operator === ts.SyntaxKind.MinusToken ? "operator: -x" : "operator: x++");
		if (ts.isBinaryExpression(n) && (DM_BINARY[n.operatorToken.kind] || DM_NEGATED[n.operatorToken.kind])) {
			const neg = !DM_BINARY[n.operatorToken.kind], [a, b] = opTok(n), fn = opFn(DM_BINARY[n.operatorToken.kind] ?? DM_NEGATED[n.operatorToken.kind], n);
			cuts.push([n.getStart(sf), n.getStart(sf), `${neg ? "!" : ""}${fn}(`]);
			visit(n.left);
			cuts.push([a, b, ","]);
			visit(n.right);
			cuts.push([n.end, n.end, ")"]);
			return;
		}
		if (ts.isBinaryExpression(n)) { // x op= v
			const [a, b] = opTok(n), fn = opFn(DM_ASSIGN[n.operatorToken.kind], n), t = target(n.left, n), s = n.getStart(sf);
			if (t.kind === "src") cuts.push([s, b, `rt.modSrcVar(f, ${JSON.stringify(t.name)},`]);
			else if (t.kind === "glob") { cuts.push([s, b, `$ml(${t.k},`]); }
			else if (t.kind === "field") {
				cuts.push([s, s, "rt.modField(f, "]);
				visit(t.recv);
				cuts.push([t.recv.end, b, `, ${JSON.stringify(t.name)},`]);
			} else cuts.push([a, b, `= rt.modify(${t.text},`]);
			if (/\n/.test(text.slice(s, b))) stop(n, "x op= v split over lines before the operator");
			visit(n.right);
			cuts.push([n.end, n.end, `, ${fn})`]);
			return;
		}
		const v = n.operand, s = n.getStart(sf);
		if (n.operator === ts.SyntaxKind.MinusToken) {
			if (/\n/.test(text.slice(s, v.getStart(sf)))) stop(n, "a - split from its operand over lines");
			cuts.push([s, v.getStart(sf), "rt.neg("]);
			visit(v);
			cuts.push([n.end, n.end, ")"]);
			return;
		}
		// x++ / ++x / x-- / --x
		const d = n.operator === ts.SyntaxKind.PlusPlusToken ? 1 : -1, post = ts.isPostfixUnaryExpression(n), t = target(v, n), tok = post ? n.end - 2 : s;
		const used = !(ts.isExpressionStatement(n.parent) || (ts.isForStatement(n.parent) && n.parent.incrementor === n));
		if (t.kind === "src") cuts.push([s, n.end, `rt.incSrcVar(f, ${JSON.stringify(t.name)}, ${d}, ${post})`]);
		else if (t.kind === "glob") { cuts.push([s, n.end, `$il(${t.k}, ${d}, ${post})`]); }
		else if (t.kind === "field") {
			cuts.push([s, t.recv.getStart(sf), "rt.incField(f, "]);
			visit(t.recv);
			cuts.push([t.recv.end, n.end, `, ${JSON.stringify(t.name)}, ${d}, ${post})`]);
		} else {
			if (used && post) stop(n, `${n.getText(sf)} used as a value on a local: write ${t.text} = rt.inc(${t.text}, ${d}) after, or ${post ? (d > 0 ? "++" : "--") + t.text : ""}`);
			const r = `${t.text} = rt.inc(${t.text}, ${d})`;
			cuts.push([s, n.end, used ? `(${r})` : r]);
		}
		if (/\n/.test(text.slice(s, n.end)) && t.kind !== "field") stop(n, "x++ split over lines");
	};
	const isOp = (n) => {
		if (ts.isBinaryExpression(n)) {
			const k = n.operatorToken.kind;
			if (BIT_OPS.has(k)) stop(n, "a plain bit operator in a proc: DM's are written as calls (rt.bitOr(a, b), rt.bitAnd, rt.bitXor, rt.shiftLeft, rt.shiftRight: 16 bits, and lists)");
			return !!(DM_BINARY[k] || DM_NEGATED[k] || DM_ASSIGN[k]);
		}
		if (ts.isPrefixUnaryExpression(n) && n.operator === ts.SyntaxKind.TildeToken) stop(n, "a plain ~ in a proc: DM's is rt.op(f, \"BitNot\", [], [a]) (16 bits)");
		if (ts.isPrefixUnaryExpression(n) && n.operator === ts.SyntaxKind.MinusToken) return !constNeg(n);
		return (ts.isPrefixUnaryExpression(n) || ts.isPostfixUnaryExpression(n)) && (n.operator === ts.SyntaxKind.PlusPlusToken || n.operator === ts.SyntaxKind.MinusMinusToken);
	};
	/**
	 * dt-builtins (detranslate step 9c): `prob(p)` / `pick(a, b)` in a proc (proc-calls.mjs DM_BUILTINS) -> rt.op(f, "Prob", [], [p]) /
	 * rt.op(f, "PickUnweighted", [2], [a, b]), as the translator wrote them; an exact column on the name goes to rt.op's.
	 */
	/**
	 * dt-text (detranslate step 9d): a template string in a proc is DM's text with embedded values: `${x}-punch` ->
	 * fmt("＀-punch", [x]) (each `${}` a `＀`: an atom's improper name gets "the", numbers DM's format). Its text's line breaks stay
	 * on their lines; a DM text macro character (U+FF01-U+FFFF: \the, \ref...) in one stops the bundle: those are fmt's.
	 */
	const lowerTemplate = (n) => {
		const parts = [n.head, ...n.templateSpans.map((x) => x.literal)];
		if (parts.some((x) => x.text === undefined)) stop(n, "a template string with an escape JS can't read");
		if (parts.some((x) => /[\uFF00-\uFFFF]/.test(x.text))) stop(n, "a DM text macro character in a template string: write fmt(\"...\", [values])");
		const fn = opFunction("fmt", n, aliases, names.scope), es = n.templateSpans.map((x) => x.expression);
		const nl = (a, b) => text.slice(a, b).replace(/[^\n]/g, "");
		rewrote("template text");
		cuts.push([n.getStart(sf), es[0].getStart(sf), `${fn}(${JSON.stringify(parts.map((x) => x.text).join("＀"))}, [${nl(n.getStart(sf), es[0].getStart(sf))}`]);
		es.forEach((e, i) => {
			visit(e);
			if (i + 1 < es.length) cuts.push([e.end, es[i + 1].getStart(sf), `, ${nl(e.end, es[i + 1].getStart(sf))}`]);
			else cuts.push([e.end, n.end, `${nl(e.end, n.end)}])`]);
		});
	};
	const lowerBuiltin = (n) => {
		const e = n.expression, op = DM_BUILTINS[e.text], close = n.end - 1, open = n.arguments.pos, a = e.getStart(sf);
		if (!procFunction(n)) stop(n, `${e.text}() outside rt.def/rt.tail, where it isn't defined (no frame f)`);
		if (n.arguments.some(ts.isSpreadElement)) stop(n, `${e.text}() with ...spread arguments`);
		if (op === "Prob" ? n.arguments.length !== 1 : n.arguments.length === 0) stop(n, `${e.text}() with ${n.arguments.length} arguments`);
		if (ts.isYieldExpression(n.parent)) stop(n, `${e.text}() never waits: no yield* before it`);
		if (text[close] !== ")" || text[open - 1] !== "(" || /\n/.test(text.slice(a, open))) stop(n, `a ${e.text}() call the bundler can't take apart`);
		rewrote(`built-in: ${e.text}`);
		cuts.push([a, open, `rt.op(f, "${op}", [${op === "Prob" ? "" : n.arguments.length}], [`]);
		for (const x of n.arguments) visit(x);
		cuts.push([close, n.end, "])"]);
	};
	/**
	 * dt-loops (detranslate step 9h): `for (M of each(L, T("/mob"))) {` in a proc (proc-calls.mjs isEachLoop) -> the translator's
	 * `rt.forList(f, K, L, T("/mob")); while (($e = rt.next(f, K)) !== undefined) { M = $e;` on its line, and `} rt.endFor(f, K);`
	 * (K: eachSlot). The proc gets `let $e;` (varsCut) unless it declares one. An exact column on each goes to forList's name.
	 */
	const lowerEach = (n) => {
		const fn = procFunction(n), a = n.expression.arguments, body = n.statement;
		if (nearestFunction(n) !== fn) stop(n, "an each() loop inside a nested function (no enumerator slots there)");
		if (!ts.isIdentifier(n.initializer)) stop(n, "an each() loop's variable must be a local declared at the top (`let M: Value = null;`, then `for (M of each(L))`)");
		if (a.length < 1 || a.length > 2 || a.some(ts.isSpreadElement)) stop(n, "each(list) or each(list, T(\"/type\"))");
		if (!ts.isBlock(body)) stop(n, "an each() loop's body must be a { block }");
		const last = a[a.length - 1], k = eachSlot(n, names.scope), x = n.initializer.text;
		if (/\n/.test(text.slice(n.getStart(sf), a[0].getStart(sf))) || /\n/.test(text.slice(last.end, body.getStart(sf) + 1))) stop(n, "an each() loop's head split over lines");
		rewrote("each loop");
		cuts.push([n.getStart(sf), a[0].getStart(sf), `rt.forList(f, ${k}, `]);
		for (const y of a) visit(y);
		cuts.push([last.end, body.getStart(sf) + 1, `); while (($e = rt.next(f, ${k})) !== undefined) { ${x} = $e;`]);
		visit(body);
		cuts.push([body.end, body.end, ` rt.endFor(f, ${k});`]);
	};
	const visit = (n) => {
		if (defineTable.size && isDefineUse(n, defineTable, names.scope)) { cuts.push([n.getStart(sf), n.end, defineTable.get(n.text)]); rewrote("define"); return; }
		if (isEachLoop(n, names.scope)) return lowerEach(n);
		if (isNewCall(n, names.scope)) { // dt-new (detranslate step 9k): new_(T, a, b) -> rt.new_(f, T, [a, b]); under yield* g.new_
			const a = n.arguments, s = n.expression.getStart(sf), close = n.end - 1, pre = ts.isYieldExpression(n.parent) && n.parent.asteriskToken ? "g" : "rt";
			if (!a.length || a.some(ts.isSpreadElement) || text[close] !== ")") stop(n, "new_(type, values...) without ...spread");
			rewrote("new_");
			cuts.push([s, a[0].getStart(sf), `${pre}.new_(f, `]);
			visit(a[0]);
			const nobj = namedObj(n), rest = nobj ? a.slice(1, -1) : a.slice(1); // dt-named (step 10a): a last `{ key: value }` is the named arguments
			if (ts.isObjectLiteralExpression(a[0]) || rest.some(ts.isObjectLiteralExpression) || (nobj && a.length < 2)) stop(n, "new_(type, ...) takes named arguments `{ key: value }` only as the last argument, after the type");
			if (a.length === 1) { cuts.push([a[0].end, n.end, ", [])"]); return; }
			const comma = text.indexOf(",", a[0].end);
			cuts.push([comma, comma + 1, ", ["]);
			for (const x of rest) { if (nobj) cuts.push([x.getStart(sf), x.getStart(sf), "null, "]); visit(x); }
			if (nobj) lowerNamed(nobj);
			cuts.push([close, n.end, nobj ? "], rt.Args.Named)" : "])"]);
			return;
		}
		if (isListCall(n, names.scope)) { // dt-list (detranslate step 9j): list(a, b) -> rt.list(a, b); an exact column on list stays on it
			const a = n.expression.getStart(sf);
			rewrote("list");
			cuts.push([a, a, "rt."]);
			for (const x of n.arguments) visit(x);
			return;
		}
		if (ts.isCallExpression(n) && ts.isIdentifier(n.expression) && n.expression.text === "each" && procFunction(n) && !names.scope.all(n).has("each"))
			stop(n, "each() is only a for...of loop's list: for (M of each(L))");
		if (ts.isBinaryExpression(n) && n.operatorToken.kind === ts.SyntaxKind.QuestionQuestionEqualsToken && procFunction(n)) {
			/**
			 * dt-defaults (detranslate step 10c): a statement `x ??= v;` (a bare name) is DM's argument default, written as the translator did:
			 * `if (x === null) { x = v; }` on the same line. Any other `??=` in a proc (a property or element on the left, used as a value, the
			 * body of an if without braces) stops the build, so nobody writes one that means something else.
			 */
			const st = n.parent;
			if (!ts.isIdentifier(n.left)) stop(n, "`??=` takes a bare name on the left (`x ??= 20;` is a DM argument default, if x is null it becomes 20)");
			if (!ts.isExpressionStatement(st) || st.expression !== n) stop(n, "`??=` is a statement of its own (`x ??= 20;`), not a value");
			if (!(ts.isBlock(st.parent) || ts.isCaseClause(st.parent) || ts.isDefaultClause(st.parent))) stop(n, "`??=` must stand in a block of its own, not as the body of an if/loop without braces");
			rewrote("argument default ??=");
			cuts.push([st.getStart(sf), st.getStart(sf), `if (${n.left.text} === null) { `]);
			cuts.push([n.operatorToken.getStart(sf), n.operatorToken.end, "="]);
			visit(n.right);
			cuts.push([st.end, st.end, " }"]);
			return;
		}
		if ((ts.isBinaryExpression(n) || ts.isPrefixUnaryExpression(n) || ts.isPostfixUnaryExpression(n)) && procFunction(n) && isOp(n)) return lowerOp(n);
		if (ts.isCallExpression(n) && ts.isIdentifier(n.expression) && DM_BUILTINS[n.expression.text] && !names.scope.all(n).has(n.expression.text)) return lowerBuiltin(n);
		if (ts.isTemplateExpression(n) && !ts.isTaggedTemplateExpression(n.parent) && procFunction(n)) return lowerTemplate(n);
		if (ts.isBinaryExpression(n) && n.operatorToken.kind === ts.SyntaxKind.EqualsToken) {
			const gn = readableGlobal(n.left, names.scope);
			if (gn) return lowerGlobal(n.left, gn, n);
		}
		const gn = readableGlobal(n, names.scope);
		if (gn) return lowerGlobal(n, gn, null);
		if (ts.isPropertyAccessExpression(n) && ts.isIdentifier(n.expression) && n.expression.text === "GLOB" && !procFunction(n) && !names.scope.all(n).has("GLOB"))
			stop(n, "GLOB.x outside rt.def/rt.tail (only procs lower it): write rt.gl(\"x\")");
		const rc = readableCall(n, names);
		if (rc) return lowerCall(n, rc);
		if (ts.isBinaryExpression(n) && n.operatorToken.kind === ts.SyntaxKind.EqualsToken) {
			const rv = readableVar(n.left, names);
			if (rv) return lowerVar(n.left, rv, n);
		}
		const rv = readableVar(n, names);
		if (rv) return lowerVar(n, rv, null);
		if (ts.isCallExpression(n) && ts.isIdentifier(n.expression) && n.expression.text === "P") {
			// P("/path") -> `$P[k]` padded with spaces to the same length (the file's procTable, filled once at install).
			const [a] = n.arguments;
			if (n.arguments.length !== 1 || !ts.isStringLiteral(a)) unsupported(n);
			let k = procIndex.get(a.text);
			if (k === undefined) { k = procPaths.length; procIndex.set(a.text, k); procPaths.push(a.text); }
			const rep = `$P[${k}]`, len = n.end - n.getStart(sf);
			if (rep.length > len) unsupported(n);
			tally("P(path)");
			cuts.push([n.getStart(sf), n.end, rep.padEnd(len)]);
			return;
		}
		if (ts.isCallExpression(n) && ts.isPropertyAccessExpression(n.expression) && ts.isIdentifier(n.expression.expression)
			&& SITE_KINDS[n.expression.expression.text + "." + n.expression.name.text]) {
			// the callee g.callName / g.callSrc (rt.callName / rt.callSrc) with a literal name -> `$.sK` (`$M.sK`) padded
			// to the same length: the file's K-th call site, a function with its own method cache (rt.methodSite). The
			// property name sits at the old one's column, which is where V8 reports the call.
			const kind = SITE_KINDS[n.expression.expression.text + "." + n.expression.name.text];
			const nameArg = n.arguments[kind === "n" || kind === "N" ? 2 : 1];
			const sites = kind === "n" || kind === "s" || kind === "t" ? gSites : rtSites, obj = sites === gSites ? "$" : "$M";
			const rep = `${obj}.s${sites.length}`, a = n.expression.getStart(sf), len = n.expression.end - a;
			if (nameArg && ts.isStringLiteral(nameArg) && rep.length <= len) {
				sites.push(kind);
				tally("old spelling: call site cache");
				cuts.push([a, n.expression.end, rep.padEnd(len)]);
			}
		}
		if (ts.isCallExpression(n) && ts.isPropertyAccessExpression(n.expression) && ts.isIdentifier(n.expression.expression)
			&& n.expression.expression.text === "rt" && n.expression.name.text === "sv" && n.arguments.length === 2 && ts.isStringLiteral(n.arguments[1])) {
			// rt.sv(f, "name") -> `$v(f,$q[K])` ($v = rt.srcVarI; $q = the file's own table of sv slots, K = this site's slot, kept apart from
			// the file's `$ic` list so its indexes stay valid), padded with trailing spaces to the same length so the columns after it stay put.
			const a0 = n.arguments[0].getText(sf), k = svNames.length;
			const rep = `$v(${a0},$q[${k}])`, a = n.getStart(sf), len = n.end - a;
			if (rep.length > len) unsupported(n);
			svNames.push(n.arguments[1].text); tally("old spelling: rt.sv");
			cuts.push([a, n.end, rep.padEnd(len)]);
			ts.forEachChild(n.arguments[0], visit);
			return;
		}
		if (ts.isCallExpression(n) && ts.isPropertyAccessExpression(n.expression) && ts.isIdentifier(n.expression.expression)
			&& n.expression.expression.text === "rt" && n.expression.name.text === "setSv" && n.arguments.length === 3 && ts.isStringLiteral(n.arguments[1])) {
			// rt.setSv(f, "name", v) -> `$s(f,$q[K],` + the untouched value text + `)`; same slot counter and `$q` table as rt.sv; only the
			// text before the value is replaced (padded with trailing spaces to its length), so the value's own cuts and all columns stay put.
			const a0 = n.arguments[0].getText(sf), k = svNames.length;
			const rep = `$s(${a0},$q[${k}],`, a = n.getStart(sf), b = n.arguments[2].getStart(sf);
			if (rep.length > b - a || /\n/.test(text.slice(a, b))) unsupported(n);
			svNames.push(n.arguments[1].text); tally("old spelling: rt.setSv");
			cuts.push([a, b, rep.padEnd(b - a)]);
			ts.forEachChild(n.arguments[0], visit);
			visit(n.arguments[2]);
			return;
		}
		if (ts.isCallExpression(n) && ts.isPropertyAccessExpression(n.expression) && ts.isIdentifier(n.expression.expression)
			&& n.expression.expression.text === "rt" && FV_KINDS[n.expression.name.text] && n.arguments.length === FV_KINDS[n.expression.name.text][1]
			&& ts.isStringLiteral(n.arguments[1])) {
			// 7d-3/7d-4: rt.fv(f, "name", OBJ) -> `$g(f,$q[K],` + the untouched OBJ text + `)` ($g = rt.fieldQ, fieldI with the cache before the object);
			// rt.setFv(f, "name", OBJ, v) -> `$F(f,$q[K],OBJ, v)` (setQ). The name goes first so the prefix is always
			// longer than the lowered one (padded), and OBJ and everything after it keep their column.
			const a0 = n.arguments[0].getText(sf), k = svNames.length, kind = FV_KINDS[n.expression.name.text];
			const rep = `${kind[0]}(${a0},$q[${k}],`, a = n.getStart(sf), b = n.arguments[2].getStart(sf);
			if (rep.length > b - a || /\n/.test(text.slice(a, b))) unsupported(n);
			svNames.push(n.arguments[1].text); tally(`old spelling: rt.${n.expression.name.text}`);
			cuts.push([a, b, rep.padEnd(b - a)]);
			ts.forEachChild(n.arguments[0], visit);
			for (let i = 2; i < n.arguments.length; i++) visit(n.arguments[i]);
			return;
		}
		if (ts.isCallExpression(n) && ts.isPropertyAccessExpression(n.expression) && ts.isIdentifier(n.expression.expression)
			&& n.expression.expression.text === "rt" && GL_KINDS[n.expression.name.text] && n.arguments.length === GL_KINDS[n.expression.name.text][1]
			&& ts.isStringLiteral(n.arguments[0])) {
			// rt.gl("name") -> `$gl(K)` (K = the global's index in game/_globals.ts, $gl = rt.glob); rt.setGl("name", v) -> `$sl(K, ` + v + `)` (setGlob);
			// rt.modGl -> `$ml(K, ` (modGlob), rt.incGl -> `$il(K, ` (incGlob). Padded with trailing spaces to the source length (the prefix up to the
			// first remaining argument), so every column after it stays put. An unknown name is a bundle error.
			const kind = n.expression.name.text, al = GL_KINDS[kind][0], k = glKeys.get(n.arguments[0].text);
			const line = sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1;
			if (k === undefined) throw new Error(`${relative(web, f)}:${line}: rt.${kind}("${n.arguments[0].text}"): no such global in game/_globals.ts`);
			const a = n.getStart(sf);
			const b = kind === "gl" ? n.end : n.arguments[1].getStart(sf);
			const rep = kind === "gl" ? `${al}(${k})` : `${al}(${k}, `;
			if (rep.length > b - a || /\n/.test(text.slice(a, b))) throw new Error(`${relative(web, f)}:${line}: rt.${kind}("${n.arguments[0].text}") doesn't lower in place`);
			tally(`old spelling: rt.${kind}`); hasGl = true;
			cuts.push([a, b, rep.padEnd(b - a)]);
			for (let i = 1; i < n.arguments.length; i++) visit(n.arguments[i]);
			return;
		}
		if (ts.isImportDeclaration(n)) {
			if (!/^#runtime$|(^|\/)dist\/src\/translate\/runtime\.js$/.test(n.moduleSpecifier.text)) unsupported(n); // the bundle imports the runtime once
			cuts.push([n.getStart(sf), n.end, true]);
			return;
		}
		if ((ts.isParameter(n) || ts.isVariableDeclaration(n)) && n.type) {
			if (n.questionToken || n.exclamationToken) unsupported(n);
			cuts.push([n.name.end, n.type.end, false]);
			if (n.initializer) visit(n.initializer);
			if (!ts.isIdentifier(n.name)) visit(n.name);
			return;
		}
		if (ts.isTypeNode(n) || ts.isAsExpression(n) || ts.isNonNullExpression(n) || ts.isTypeAssertionExpression(n) || ts.isSatisfiesExpression(n)
			|| ts.isInterfaceDeclaration(n) || ts.isTypeAliasDeclaration(n) || ts.isEnumDeclaration(n) || ts.isModuleDeclaration(n)
			|| ts.isClassLike(n) || ts.isExportDeclaration(n) || ts.isExportAssignment(n) || ts.isDecorator(n)
			|| ((ts.isFunctionLike(n)) && (n.type || n.typeParameters)) || ((ts.isCallExpression(n) || ts.isNewExpression(n)) && n.typeArguments)
			|| (ts.canHaveModifiers(n) && ts.getModifiers(n)?.length)) unsupported(n);
		ts.forEachChild(n, visit);
	};
	for (const st of sf.statements) {
		const e = ts.isExpressionStatement(st) ? st.expression : null;
		if (e && ts.isCallExpression(e) && ts.isPropertyAccessExpression(e.expression) && ts.isIdentifier(e.expression.expression)
			&& e.expression.expression.text === "rt" && e.expression.name.text === "def")
			defs.push(sf.getLineAndCharacterOfPosition(st.getStart(sf)).line + 1, e.arguments[0].text);
		if (e && ts.isCallExpression(e) && ts.isPropertyAccessExpression(e.expression) && ts.isIdentifier(e.expression.expression)
			&& e.expression.expression.text === "rt" && (e.expression.name.text === "def" || e.expression.name.text === "tail") && e.arguments[1] && ts.isFunctionExpression(e.arguments[1])) {
			const fn = e.arguments[1];
			let each = false;
			const look = (x) => { if (each || (x !== fn && ts.isFunctionLike(x))) return; if (isEachLoop(x, names.scope)) each = true; else ts.forEachChild(x, look); };
			look(fn);
			const c = varsCut(fn, sf, text, stop, each && !declaredNames(fn).has("$e"));
			if (c) { cuts.push(...c); tally("f.vars"); }
		}
		visit(st);
	}
	const typeImp = sf.statements.find((x) => ts.isImportDeclaration(x) && x.importClause?.isTypeOnly && x.importClause.namedBindings?.elements?.map((e) => e.name.text).join() === "Frame,Value");
	if (typeImp) { // the line after it holds the file's `const { names } = rt;`, or nothing when it uses none: the bundle gets the full one
		const a = text.indexOf("\n", typeImp.end) + 1, b = text.indexOf("\n", a);
		const old = text.slice(a, b < 0 ? text.length : b);
		if (a > 0 && old !== "" && !/^const \{ [A-Za-z, ]+ \} = rt;$/.test(old)) stop(typeImp, "the line after the type import is `const { names } = rt;` or empty");
		if (a > 0 && !/^const \{ T, P, g, truthy, isEqual, add, fmt \} = rt;$/.test(old)) { cuts.push([a, a + old.length, RT_NAMES]); tally("rt names line"); }
	}
	// at one position an insert goes before a cut that replaces text there (an operator's `)` before its call's `])`)
	cuts.sort((x, y) => x[0] - y[0] || (y[0] === y[1]) - (x[0] === x[1]));
	if (procPaths.length) { // the table goes on the (blanked) first import line
		const imp = cuts.find((c) => c[2] === true);
		if (!imp) throw new Error(`${relative(web, f)}: P("...") calls but no import line to put the proc table on`);
		imp[3] = `const $P = rt.procTable(${JSON.stringify(relative(src, f))}, ${JSON.stringify(procPaths)});`;
	}
	if (gSites.length || rtSites.length) { // the call-site tables too
		const imp = cuts.find((c) => c[2] === true);
		if (!imp) throw new Error(`${relative(web, f)}: method calls but no import line to put the call-site tables on`);
		const table = (name, kinds) => kinds.length ? `const ${name} = {${kinds.map((k, i) => `s${i}: rt.methodSite("${k}")`).join(", ")}};` : "";
		imp[3] = (imp[3] ?? "") + table("$", gSites) + table("$M", rtSites);
	}
	if (svNames.length) { // the slots and the alias
		const imp = cuts.find((c) => c[2] === true);
		if (!imp) throw new Error(`${relative(web, f)}: rt.sv sites but no import line to put the slot table on`);
		const list = svNames.map((x) => JSON.stringify(x)).join(", ");
		imp[3] = (imp[3] ?? "") + `const $v = rt.srcVarI, $s = rt.setSrcVarI, $g = rt.fieldQ, $F = rt.setQ, $q = rt.fieldICs([${list}]);`;
	}
	if (hasGl) { // the aliases
		const imp = cuts.find((c) => c[2] === true);
		if (!imp) throw new Error(`${relative(web, f)}: rt.gl sites but no import line to put the aliases on`);
		imp[3] = (imp[3] ?? "") + "const $gl = rt.glob, $sl = rt.setGlob, $ml = rt.modGlob, $il = rt.incGlob;";
	}
	let body = "", at = 0;
	for (const [a, b, how, pre] of cuts) {
		body += text.slice(at, a);
		const r = typeof how === "string" ? how : how ? (pre ?? "") + text.slice(a, b).replace(/[^\n]/g, "") : text.slice(a, b).replace(/[^\n]/g, " ");
		body += r;
		at = b;
	}
	body += text.slice(at);
	if (body.endsWith("\n")) body = body.slice(0, -1); // the block's closing brace goes on the next line
	if (sf.parseDiagnostics?.length) { bad++; console.error(`${relative(web, f)}: ${ts.flattenDiagnosticMessageText(sf.parseDiagnostics[0].messageText, "\n")}`); }
	return { body, defs };
}
// the proc bundle keeps every game file's lines and columns (type annotations and imports blanked out, cut
// declarations left as empty lines), so a JS stack position in translated-tg.js is game file:line:column after one
// subtraction. build/translated-tg.lines.json (read only when a runtime error happens; src/translate/error-lines.ts) has
// each file's first bundle line and its rt.def lines.
let bundleLine = bundle.length + 1; // 1-based line of the next bundle line
const lineFiles = [], lineStarts = [], lineDefs = [];
for (let fi = 0; fi < files.length; fi++) {
	const f = files[fi], text = readFileSync(hotOut ? hotText[fi] : f, "utf8"), before = nDecl, typesAt = typesBundle.length;
	if (hotEach) { // the error a file stops on (thrown, or a syntax error's console.error), kept as its result
		const said = [], badAt = bad, err = console.error;
		console.error = (...a) => said.push(a.join(" "));
		try {
			const { body, defs } = blankTypes(f, splitDecls(f, text));
			hotRes.push(bad > badAt ? { file: relative(src, f), err: said.join("\n") } : { file: relative(src, f), types: oneByte(typesBundle.slice(typesAt).join("\n"), "types"), body: oneByte(body, "body"), defs: defs.filter((_, i) => i % 2) });
		} catch (e) { hotRes.push({ file: relative(src, f), err: [...said, e.stack ?? String(e)].join("\n") }); }
		console.error = err; bad = badAt;
		continue;
	}
	const { body, defs } = blankTypes(f, splitDecls(f, text));
	if (hotOut) { hotRes.push({ file: relative(src, f), types: oneByte(typesBundle.slice(typesAt).join("\n"), "types"), body: oneByte(body, "body"), defs: defs.filter((_, i) => i % 2) }); continue; }
	const hadDecls = nDecl > before;
	if (!hadDecls && !IMPORT_RE.test(text)) throw new Error(`${relative(web, f)}: no runtime import line to strip for the bundle`);
	const o = resolve(out, relative(src, f)).replace(/\.ts$/, ".js");
	mkdirSync(dirname(o), { recursive: true });
	writeFileSync(o, body);
	bundle.push(`{ // ${relative(src, f)}`);
	lineFiles.push(relative(src, f));
	lineStarts.push(bundleLine + 1);
	lineDefs.push(defs);
	bundle.push(body, "}");
	bundleLine += 2 + body.split("\n").length;
}
// Characters above U+00FF (mostly fmt's ＀ placeholder) are written as \uXXXX escapes: one such character makes V8 keep
// the whole 27 MB source as two bytes per character, so this saves ~30 MB of memory. Line numbers are unchanged.
// A backslash right before one would turn the escape into a literal "\u...", so that stops the build.
function oneByte(text, name) {
	const bad = /\\[^\x00-\xff]/.exec(text);
	if (bad) throw new Error(`${name}: backslash before a character above U+00FF at offset ${bad.index}`);
	return text.replace(/[^\x00-\xff]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
}
if (bad) { console.error(`[translate-tg] ${bad} file(s) with syntax errors (above); translated-tg.js and game-types.js not written (old ones kept)`); process.exit(1); }
if (hotOut) { writeFileSync(hotOut, JSON.stringify(hotRes)); process.exit(0); }
writeFileSync(resolve(web, "build/translated-tg.js"), oneByte(bundle.join("\n") + "\n", "translated-tg.js"));
writeFileSync(resolve(web, "build/game-types.js"), oneByte(typesBundle.join("\n") + "\n", "game-types.js"));
writeFileSync(resolve(web, "build/translated-tg.lines.json"), JSON.stringify({ files: lineFiles, starts: lineStarts, defs: lineDefs }));
const rewrites = Object.values(meter).reduce((a, b) => a + b, 0);
writeFileSync(resolve(web, "build/rewrite-meter.json"), JSON.stringify({ total: rewrites, kinds: Object.fromEntries(Object.entries(meter).sort((a, b) => b[1] - a[1])) }, null, "\t") + "\n");
